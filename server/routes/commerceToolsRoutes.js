const express = require("express");
const { protect, adminOnly } = require("../middleware/auth");
const c = require("../controllers/commerceToolsController");
const router = express.Router();
router.get("/coupons", c.publicCoupons);
router.post("/coupons/preview", protect, c.previewCoupon);
router.get("/wishlist", protect, c.wishlist);
router.get("/wishlist/ids", protect, c.wishlistIds);
router.put("/wishlist/:id", protect, c.saveWish);
router.delete("/wishlist/entries/:id", protect, c.removeWishEntry);
router.delete("/wishlist/:id", protect, c.removeWish);
router.get("/admin/coupons", protect, adminOnly, c.listCoupons);
router.post("/admin/coupons", protect, adminOnly, c.saveCoupon);
router.put("/admin/coupons/:id", protect, adminOnly, c.saveCoupon);
router.get("/admin/store-settings", protect, adminOnly, c.getConfig);
router.put("/admin/store-settings", protect, adminOnly, c.saveConfig);
router.get("/admin/inventory", protect, adminOnly, c.listInventory);
router.get("/admin/inventory/export.csv", protect, adminOnly, c.exportInventory);
router.post("/admin/inventory/preview", protect, adminOnly, c.previewInventory);
router.post("/admin/inventory/import", protect, adminOnly, c.applyInventory);
router.get("/admin/inventory/imports/:id", protect, adminOnly, c.getImport);
module.exports = router;
